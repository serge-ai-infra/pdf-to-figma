#!/usr/bin/env bash
#
# probe-pdf.sh — find out what a PDF is actually made of before trying to
# reproduce it. Read-only: never modifies the input.
#
# Reports page geometry, embedded fonts, the palette, how text is encoded, and
# per-page SVG/PNG conversions with node counts, so the cost and the ceiling of
# a rebuild can be estimated from facts instead of assumptions.
#
# Usage: ./scripts/probe-pdf.sh <input.pdf> [outdir] [dpi]
#
set -euo pipefail

usage() {
    sed -n '3,12p' "$0" | sed 's/^# \{0,1\}//'
    exit "${1:-0}"
}

[ $# -ge 1 ] || usage 1
case "$1" in -h | --help) usage 0 ;; esac

INPUT="$1"
OUTDIR="${2:-work/probe}"
DPI="${3:-200}"

[ -f "$INPUT" ] || { echo "error: no such file: $INPUT" >&2; exit 1; }

# Resolve tools up front — PATH is not reliable inside subshells and loops.
for tool in pdfinfo pdffonts pdftocairo pdftoppm; do
    path="$(command -v "$tool" || true)"
    [ -n "$path" ] || {
        echo "error: $tool not found. Install poppler (brew install poppler)." >&2
        exit 1
    }
    eval "BIN_${tool}=\$path"
done

mkdir -p "$OUTDIR/svg" "$OUTDIR/png"
REPORT="$OUTDIR/report.md"

# Count occurrences, not matching lines: generated SVG may put many nodes on one
# line. wc always exits 0, which keeps `set -e` from firing on zero matches.
# A zero-match grep exits 1, which pipefail would turn into a script abort.
count_in() { { LC_ALL=C grep -o -a -- "$2" "$1" 2>/dev/null || true; } | wc -l | tr -d ' '; }

"$BIN_pdfinfo" "$INPUT" > "$OUTDIR/info.txt"
"$BIN_pdffonts" "$INPUT" > "$OUTDIR/fonts.txt"

PAGES="$(awk '/^Pages:/ {print $2}' "$OUTDIR/info.txt")"
PAGESIZE="$(awk -F': +' '/^Page size:/ {print $2}' "$OUTDIR/info.txt" | head -1)"
PRODUCER="$(awk -F': +' '/^Producer:/ {print $2}' "$OUTDIR/info.txt" | head -1)"
CREATOR="$(awk -F': +' '/^Creator:/ {print $2}' "$OUTDIR/info.txt" | head -1)"

FONT_TOTAL="$(awk 'NR>2 && NF {c++} END {print c+0}' "$OUTDIR/fonts.txt")"
FONT_EMBEDDED="$(awk 'NR>2 && NF && $0 ~ / yes /  {c++} END {print c+0}' "$OUTDIR/fonts.txt")"
FONT_SUBSET="$(awk 'NR>2 && NF && $1 ~ /^[A-Z]{6}\+/ {c++} END {print c+0}' "$OUTDIR/fonts.txt")"

{
    echo "# PDF probe report"
    echo
    echo "Generated by \`scripts/probe-pdf.sh\`. The input path is deliberately not"
    echo "recorded — reports stay shareable without disclosing the source document."
    echo
    echo "## Document"
    echo
    echo "- Pages: $PAGES"
    echo "- Page size: $PAGESIZE"
    echo "- Producer: ${PRODUCER:-unknown}"
    echo "- Creator: ${CREATOR:-unknown}"
    echo
    echo "A programmatic producer (a reporting library rather than a design tool)"
    echo "means the document has a generator upstream. If that generator is"
    echo "available, reverse-engineering the PDF is the harder path to the same"
    echo "information."
    echo
    echo "## Fonts"
    echo
    echo "- Total: $FONT_TOTAL"
    echo "- Embedded: $FONT_EMBEDDED"
    echo "- Subsetted (TAG+Name): $FONT_SUBSET"
    echo
    echo "Embedded subsets need repair before the OS can install them, and Figma"
    echo "can only use fonts installed in the OS. Non-embedded fonts cannot be"
    echo "recovered from the document at all — but the PDF standard-14 families"
    echo "are present on most systems already, which removes the problem instead"
    echo "of creating it."
    echo
    echo '```'
    cat "$OUTDIR/fonts.txt"
    echo '```'
} > "$REPORT"

page=1
declare -a ROWS=()
while [ "$page" -le "$PAGES" ]; do
    svg="$OUTDIR/svg/page-$page.svg"
    "$BIN_pdftocairo" -svg -f "$page" -l "$page" "$INPUT" "$svg"
    "$BIN_pdftoppm" -png -r "$DPI" -f "$page" -l "$page" "$INPUT" "$OUTDIR/png/page"

    svg_kb=$(( ( $(wc -c < "$svg") + 1023 ) / 1024 ))
    paths="$(count_in "$svg" '<path')"
    texts="$(count_in "$svg" '<text')"
    images="$(count_in "$svg" '<image')"
    uses="$(count_in "$svg" '<use')"
    symbols="$(count_in "$svg" '<symbol')"
    if LC_ALL=C grep -q -a '@font-face' "$svg" 2>/dev/null; then fontface=yes; else fontface=no; fi

    ROWS+=("$page, $svg_kb, $paths, $texts, $symbols, $uses, $images, $fontface")
    page=$(( page + 1 ))
done

# Palette straight out of the vector conversion. Cairo emits percentages; these
# are the document's actual fills, which is also an implicit color-space check:
# a converted CMYK source shows up as off-round percentages everywhere.
COLORS="$OUTDIR/colors.txt"
LC_ALL=C grep -o -a -h 'rgb([0-9.%, ]*)' "$OUTDIR"/svg/*.svg 2>/dev/null \
    | sort | uniq -c | sort -rn > "$COLORS" || true
COLOR_COUNT="$(wc -l < "$COLORS" | tr -d ' ')"

{
    echo
    echo "## Text encoding and node counts"
    echo
    echo "\`<text>\` nodes mean live, selectable text — which Figma will re-render"
    echo "in a substituted font, because it ignores \`@font-face\` in imported SVG."
    echo "\`<symbol>\` plus \`<use>\` means every glyph became an outline: pixel-exact"
    echo "and dead. Either way, live text has to be emitted by the builder from the"
    echo "IR, not inherited from the SVG."
    echo
    echo "page, svg KB, paths, text nodes, glyph symbols, uses, images, has @font-face"
    for row in "${ROWS[@]}"; do echo "$row"; done
    echo
    echo "## Palette"
    echo
    echo "- Distinct fill colors across all pages: $COLOR_COUNT"
    echo
    echo "Top 15 by frequency (see \`colors.txt\` for the full list):"
    echo
    echo '```'
    head -15 "$COLORS"
    echo '```'
    echo
    echo "## Artifacts"
    echo
    echo "- \`info.txt\`, \`fonts.txt\` — raw poppler output"
    echo "- \`colors.txt\` — every distinct fill with occurrence counts"
    echo "- \`svg/page-N.svg\` — vector conversion, candidate donor geometry"
    echo "- \`png/page-N.png\` — reference render at ${DPI} dpi, ground truth for diffing"
} >> "$REPORT"

echo "Report: $REPORT"
